"use server";

import { revalidatePath } from "next/cache";
import { z } from "zod";
import { requireUser } from "@/lib/auth";
import { prisma } from "@/lib/db";
import { complete, AiNotConfiguredError, AiRequestError } from "@/lib/ai";
import {
  DIGEST_PROMPT_HEADER,
  TUTOR_SYSTEM_PROMPT,
  buildGenerationPrompt,
  parseGeneratedQuestions,
} from "@/lib/ai";
import { serialiseStringList } from "@/lib/json-fields";
import { ALL_SKILLS, DOMAINS } from "@/lib/domain/taxonomy";
import { getWeaknesses } from "@/lib/queries";
import { ERROR_CATEGORY_LABEL, type AiProvider, type ErrorCategory } from "@/lib/domain/enums";

const GenerateSchema = z.object({
  skillId: z.string().min(1),
  difficulty: z.coerce.number().int().min(1).max(5).default(4),
  count: z.coerce.number().int().min(1).max(5).default(3),
});

export interface GenerateResult {
  ok: boolean;
  error?: string;
  added?: number;
  rejected?: number;
  rejectionDetail?: string[];
  skillName?: string;
}

/**
 * Generate practice questions into the bank.
 *
 * Generated rows go through the importer's own validation, and are stored with
 * source=ai_generated and verified=false so the answer-key warning shows during
 * practice. Both are deliberate: a model's answer key is a guess, and a wrong
 * key the student trusts actively teaches the wrong method.
 */
export async function generateQuestionsAction(input: unknown): Promise<GenerateResult> {
  const user = await requireUser();

  if (!user.settings.aiEnabled) {
    return { ok: false, error: "The AI tutor is switched off for this account." };
  }

  const parsed = GenerateSchema.safeParse(input);
  if (!parsed.success) return { ok: false, error: "Could not read that request." };

  const skill = ALL_SKILLS.find((s) => s.id === parsed.data.skillId);
  if (!skill) return { ok: false, error: "Unknown skill." };
  const domain = DOMAINS.find((d) => d.id === skill.domainId);

  // Aim the generation at patterns the student actually misses.
  const missed = await prisma.attempt.findMany({
    where: {
      userId: user.id,
      isCorrect: false,
      question: { skillId: skill.id, patternName: { not: null } },
    },
    orderBy: { createdAt: "desc" },
    take: 12,
    select: { question: { select: { patternName: true } } },
  });
  const weakPatterns = [
    ...new Set(
      missed
        .map((m) => m.question.patternName)
        .filter((name): name is string => Boolean(name)),
    ),
  ].slice(0, 4);

  const prompt = buildGenerationPrompt({
    skillId: skill.id,
    skillName: skill.name,
    domainName: domain?.name ?? skill.domainId,
    section: skill.section,
    difficulty: parsed.data.difficulty,
    count: parsed.data.count,
    weakPatterns,
  });

  let text: string;
  let model: string;
  try {
    const result = await complete(
      user.settings.aiProvider as AiProvider,
      {
        messages: [
          { role: "system", content: TUTOR_SYSTEM_PROMPT },
          { role: "user", content: prompt },
        ],
        maxTokens: 3000,
        // Some variety is wanted here, unlike for explanations.
        temperature: 0.7,
      },
      user.settings.aiModel,
    );
    text = result.text;
    model = result.model;
  } catch (error) {
    if (error instanceof AiNotConfiguredError) return { ok: false, error: error.message };
    if (error instanceof AiRequestError) {
      return { ok: false, error: `The provider rejected that request. ${error.message}` };
    }
    return {
      ok: false,
      error: error instanceof Error ? error.message : "Could not reach the AI provider.",
    };
  }

  const outcome = parseGeneratedQuestions(text);

  if (outcome.accepted.length === 0) {
    return {
      ok: false,
      skillName: skill.name,
      rejected: outcome.rejected.length,
      rejectionDetail: outcome.rejected.flatMap((r) => r.errors).slice(0, 6),
      error:
        "The model returned nothing usable. Nothing was added. Try again, or lower the count.",
    };
  }

  const batch = await prisma.importBatch.create({
    data: {
      userId: user.id,
      name: `AI generated: ${skill.name}`,
      source: "ai_generated",
      sourceRef: `Generated by ${model}`,
      licenceNote: "Generated practice material. Answer key not verified.",
      notes: weakPatterns.length > 0 ? `Aimed at: ${weakPatterns.join("; ")}` : null,
      rowsSeen: outcome.accepted.length + outcome.rejected.length,
      rowsImported: 0,
      rowsRejected: outcome.rejected.length,
      report: outcome.rejected.length > 0 ? JSON.stringify(outcome.rejected) : null,
    },
  });

  let added = 0;
  for (const row of outcome.accepted) {
    const created = await prisma.question.create({
      data: {
        skillId: row.skillId,
        section: skill.section,
        format: row.format,
        stimulus: row.stimulus ?? null,
        stimulusTitle: row.stimulusTitle ?? null,
        stem: row.stem,
        acceptedAnswers: serialiseStringList(row.acceptedAnswers),
        difficulty: row.difficulty,
        explanation: row.explanation || "No explanation was supplied.",
        patternName: row.patternName ?? null,
        concept: row.concept ?? null,
        recognitionCues: serialiseStringList(row.recognitionCues),
        fastestMethod: row.fastestMethod ?? null,
        alternativeMethod: row.alternativeMethod ?? null,
        commonTraps: serialiseStringList(row.commonTraps),
        expectedSeconds: row.expectedSeconds,
        source: "ai_generated",
        sourceRef: `Generated by ${model}`,
        licenceNote: "Generated practice material. Answer key not verified.",
        // Never verified automatically. Only a human says that.
        verified: false,
        restrictedText: false,
        authorId: user.id,
        importBatchId: batch.id,
      },
    });

    if (row.format === "mcq" && row.choices) {
      await prisma.choice.createMany({
        data: row.choices.map((choice, order) => ({
          questionId: created.id,
          label: choice.label,
          text: choice.text,
          isCorrect: choice.isCorrect,
          distractorType: choice.distractorType ?? null,
          rationale: choice.rationale ?? null,
          order,
        })),
      });
    }
    added += 1;
  }

  await prisma.importBatch.update({
    where: { id: batch.id },
    data: { rowsImported: added },
  });

  revalidatePath("/bank");
  revalidatePath("/practice");

  return {
    ok: true,
    added,
    rejected: outcome.rejected.length,
    rejectionDetail: outcome.rejected.flatMap((r) => r.errors).slice(0, 6),
    skillName: skill.name,
  };
}

export interface DigestResult {
  ok: boolean;
  error?: string;
  digest?: string;
}

/** A written analysis of the student's recurring mistakes. */
export async function generateDigestAction(): Promise<DigestResult> {
  const user = await requireUser();

  if (!user.settings.aiEnabled) {
    return { ok: false, error: "The AI tutor is switched off for this account." };
  }

  const [entries, weaknesses] = await Promise.all([
    prisma.errorLogEntry.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: "desc" },
      take: 120,
      include: {
        question: {
          select: { patternName: true, difficulty: true, skill: { select: { name: true } } },
        },
      },
    }),
    getWeaknesses(user.id, user.settings.targetScore),
  ]);

  if (entries.length < 5) {
    return {
      ok: false,
      error:
        "Not enough logged mistakes yet. Answer some questions and classify what went wrong first; a digest from four errors would be guesswork.",
    };
  }

  const tally = new Map<string, number>();
  for (const entry of entries) {
    const key = `${ERROR_CATEGORY_LABEL[entry.category as ErrorCategory] ?? entry.category} on ${entry.question.skill.name}${entry.question.patternName ? ` (${entry.question.patternName})` : ""}`;
    tally.set(key, (tally.get(key) ?? 0) + 1);
  }

  const lines = [...tally.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 15)
    .map(([label, count]) => `- ${count} x ${label}`);

  const priorities = weaknesses
    .filter((w) => w.expectedGain > 0)
    .slice(0, 5)
    .map(
      (w) =>
        `- ${w.skillName}: ${Math.round(w.recentAccuracy * 100)}% over ${w.attempts} attempts, worth about ${Math.round(w.expectedGain)} points`,
    );

  const prompt = `${DIGEST_PROMPT_HEADER}

Target score: ${user.settings.targetScore}

Logged mistakes, most frequent first:
${lines.join("\n")}

Skills ranked by points recoverable:
${priorities.length > 0 ? priorities.join("\n") : "- not enough data yet"}`;

  try {
    const result = await complete(
      user.settings.aiProvider as AiProvider,
      {
        messages: [
          { role: "system", content: TUTOR_SYSTEM_PROMPT },
          { role: "user", content: prompt },
        ],
        maxTokens: 900,
        temperature: 0.3,
      },
      user.settings.aiModel,
    );

    // Keep the digest as a thread so it is not lost on refresh.
    const thread = await prisma.tutorThread.create({
      data: {
        userId: user.id,
        intent: "mistake_review",
        provider: result.provider,
        model: result.model,
        title: `Mistake digest, ${new Date().toLocaleDateString("en-GB", { day: "numeric", month: "short" })}`,
        messages: {
          create: [
            { role: "user", content: "Analyse my recurring mistakes." },
            { role: "assistant", content: result.text },
          ],
        },
      },
    });

    revalidatePath("/tutor");
    return { ok: true, digest: result.text || `Saved as thread ${thread.id}.` };
  } catch (error) {
    if (error instanceof AiNotConfiguredError) return { ok: false, error: error.message };
    return {
      ok: false,
      error: error instanceof Error ? error.message : "Could not reach the AI provider.",
    };
  }
}
